import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { createHash } from "node:crypto";
import assert from "node:assert/strict";
import solc from "solc";

const imports = /^\s*import\s+(?:[^;]*?\bfrom\s*)?["']([^"']+)["']\s*;/gm;
const seen = new Set();
const chunks = [];
const sources = [];
const oz = JSON.parse(
  await readFile("node_modules/@openzeppelin/contracts/package.json", "utf8"),
);
assert.equal(
  oz.version,
  "5.4.0",
  "Use npm ci to install the pinned OpenZeppelin version.",
);
assert(solc.version().startsWith("0.8.28+"), "Solidity 0.8.28 is required.");

async function visit(name) {
  if (seen.has(name)) return;
  seen.add(name);
  const source = await readFile(
    name.startsWith("@") ? `node_modules/${name}` : name,
    "utf8",
  );
  // These contracts use named imports without aliases. Refuse unsupported imports
  // instead of silently changing symbol resolution when flattening future code.
  for (const match of source.matchAll(imports)) {
    assert(!/\bas\b/.test(match[0]), `Aliased import needs manual review: ${name}`);
    const target = match[1].startsWith(".")
      ? path.posix.normalize(path.posix.join(path.posix.dirname(name), match[1]))
      : match[1];
    assert(
      target.startsWith("contracts/") || target.startsWith("@openzeppelin/contracts/"),
    );
    await visit(target);
  }
  sources.push({ path: name, sha256: createHash("sha256").update(source).digest("hex") });
  const body = source
    .replace(imports, "")
    .replace(/^\s*\/\/\s*SPDX-License-Identifier:.*$/gm, "")
    .replace(/^\s*pragma solidity[^;]+;/gm, "")
    .trim();
  chunks.push(`// Source: ${name}\n${body}`);
}
await visit("contracts/LionNFT.sol");
await visit("contracts/LionMarketplace.sol");
const bundle = `// SPDX-License-Identifier: MIT\npragma solidity 0.8.28;\n\n// Generated by npm run remix:prepare. Do not edit this file directly.\n// Includes OpenZeppelin Contracts 5.4.0 (MIT).\n\n${chunks.join("\n\n")}\n`;
const config = JSON.parse(await readFile("remix/compiler_config.json", "utf8"));
const workspaceConfig = JSON.parse(await readFile("remix/remix.config.json", "utf8"));
assert.deepEqual(
  workspaceConfig["solidity-compiler"],
  config,
  "Remix workspace and legacy compiler settings must agree.",
);
const result = JSON.parse(
  solc.compile(
    JSON.stringify({
      ...config,
      sources: { "Lionverse.sol": { content: bundle } },
    }),
  ),
);
const errors = (result.errors || []).filter((error) => error.severity === "error");
assert.equal(errors.length, 0, errors.map((error) => error.formattedMessage).join("\n"));
const contracts = {};
for (const name of ["LionNFT", "LionMarketplace"]) {
  const compiled = result.contracts["Lionverse.sol"][name];
  const abi = JSON.parse(await readFile(`src/generated/${name}.abi.json`, "utf8"));
  assert.deepEqual(
    compiled.abi,
    abi,
    `${name} ABI differs from the frontend. Review and synchronize before exporting.`,
  );
  const runtimeBytes = compiled.evm.deployedBytecode.object.length / 2;
  assert(runtimeBytes <= 24576, `${name} exceeds the EVM runtime size limit.`);
  assert.deepEqual(
    compiled.evm.bytecode.linkReferences,
    {},
    "Bundle must not need library deployment/linking.",
  );
  contracts[name] = { runtimeBytes, abiMatchesFrontend: true };
}
await mkdir("remix", { recursive: true });
await writeFile("remix/Lionverse.sol", bundle);
await writeFile(
  "remix/manifest.json",
  JSON.stringify(
    {
      compiler: solc.version(),
      openzeppelin: oz.version,
      settings: config.settings,
      bundleSha256: createHash("sha256").update(bundle).digest("hex"),
      sources,
      contracts,
    },
    null,
    2,
  ) + "\n",
);
console.log(`Remix bundle ready: remix/Lionverse.sol (${sources.length} sources).`);
console.log(
  "Compiled with Solidity 0.8.28, optimizer 200, viaIR, Paris; both ABIs match the frontend.",
);

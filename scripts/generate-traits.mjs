import { readFile, writeFile } from "node:fs/promises";

// The JSON catalog is the only editable source of weights and spectrum limits.
const spec = JSON.parse(await readFile("shared/genetics.json", "utf8"));
if (spec.loci.length !== 9)
  throw new Error("Changing locus count requires a schema migration.");
for (const locus of spec.loci) {
  if (
    locus.names.length !== locus.weights.length ||
    locus.weights.some((n) => !Number.isInteger(n) || n < 1 || n > 65535)
  ) {
    throw new Error(`Invalid weights for ${locus.key}`);
  }
}
const constants = {
  VERSION: spec.version,
  LOCUS_COUNT: spec.loci.length,
  MUTATION_DENOMINATOR: spec.mutationDenominator,
  SPECTRUM_DENOMINATOR: spec.spectrum.denominator,
  FOUNDER_PRISMATIC: spec.spectrum.founderPrismatic,
  FOUNDER_MONOCHROME: spec.spectrum.founderMonochrome,
  ...Object.fromEntries(
    Object.entries(spec.spectrum.breeding).map(([k, v]) => [
      `BREED_${k.replace(/[A-Z]/g, (c) => `_${c}`).toUpperCase()}`,
      v,
    ]),
  ),
  MONO_DENOMINATOR: spec.spectrum.monochrome.denominator,
  ...Object.fromEntries(
    Object.entries(spec.spectrum.monochrome)
      .filter(([k]) => k !== "denominator")
      .map(([k, v]) => [`MONO_${k.replace(/[A-Z]/g, (c) => `_${c}`).toUpperCase()}`, v]),
  ),
};
const branches = spec.loci.map((locus, index) => {
  const thresholds = locus.weights.reduce(
    (list, weight) => [...list, weight + (list.at(-1) || 0)],
    [],
  );
  return `        if (locus == ${index}) {\n            uint256 roll = word % ${thresholds.at(-1)};\n${thresholds
    .slice(0, -1)
    .map((n, i) => `            if (roll < ${n}) return ${i};`)
    .join("\n")}\n            return ${thresholds.length - 1};\n        }`;
});
const content = `// SPDX-License-Identifier: MIT
pragma solidity ^0.8.28;

// Generated by scripts/generate-traits.mjs. Edit shared/genetics.json instead.
library TraitCatalog {
${Object.entries(constants)
  .map(([k, v]) => `    uint256 internal constant ${k} = ${v};`)
  .join("\n")}

    function draw(uint256 locus, uint256 word) internal pure returns (uint8) {
${branches.join("\n")}
        revert("Unknown locus");
    }
}
`;
const destination = "contracts/generated/TraitCatalog.sol";
if (process.argv.includes("--check")) {
  if ((await readFile(destination, "utf8")) !== content)
    throw new Error("Run npm run generate:traits; the Solidity catalog is stale.");
} else await writeFile(destination, content);
